export type Glyph = { width: number; rows: boolean[][] };

const glyphs = new Map<string, Glyph>(
  Object.entries(GLYPHS).map(([char, art]) => {
    const rows = art.split(" ").map((row) => [...row].map((p) => p === "#"));
    return [char, { width: rows[0]?.length ?? 0, rows }];
  }),
);

/** The glyphs for `text`, with accents stripped and unknown characters as `?` */
export function toGlyphs(text: string): Glyph[] {
  const plain = text.normalize("NFD").replace(/\p{Mn}/gu, "");
  return [...plain].map(
    (char) => glyphs.get(char) ?? (glyphs.get("?") as Glyph),
  );
}

/** Pixel width of `text`, one blank column between glyphs */
export function textWidth(text: string): number {
  const all = toGlyphs(text);
  const inked = all.reduce((sum, glyph) => sum + glyph.width, 0);
  return Math.max(0, inked + all.length - 1);
}
